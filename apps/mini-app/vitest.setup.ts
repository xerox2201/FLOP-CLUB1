import '@testing-library/jest-dom/vitest';

/**
 * Node 26 ships an experimental `localStorage` global that is unusable unless the
 * process is started with `--localstorage-file`, and it shadows the jsdom
 * implementation. Install a small in-memory Storage so tests that exercise
 * persistence behave like a browser.
 */
class MemoryStorage implements Storage {
  private entries = new Map<string, string>();

  get length(): number {
    return this.entries.size;
  }

  clear(): void {
    this.entries.clear();
  }

  getItem(key: string): string | null {
    return this.entries.get(key) ?? null;
  }

  key(index: number): string | null {
    return [...this.entries.keys()][index] ?? null;
  }

  removeItem(key: string): void {
    this.entries.delete(key);
  }

  setItem(key: string, value: string): void {
    this.entries.set(key, String(value));
  }
}

Object.defineProperty(globalThis, 'localStorage', {
  value: new MemoryStorage(),
  configurable: true,
  writable: true,
});
